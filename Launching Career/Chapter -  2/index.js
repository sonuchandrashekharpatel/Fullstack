/* Lesson 4: Adding a professional headshot to LinkedIn */
/* 
Making the right impression with your profile photo
    Statistics show that LinkedIn users with a profile photo receive 21x more profile views.
    And they receive 9x more connection requests and 36x more messages

    You can DIY a headshot by:
        . Asking a friend to take it
        . Cropping an existing photo
        . Attending a meetup that offers free headshots
        . Paying a professional photographer

    Tips for making a headshot
        . Find a simple background
        . Use natural light
        . Look directly at the camera
        . Wear professional attire
    
    The technical stuff
        . Make sure the image isn't too big!
        . 8MB the file size limit
        . 400px By 400px is great!
        . Avoid photos that need too much cropping

    What now?
        . Upload a headshot to linkedIn
        
*/

/* Lesson 3: Crafting a great summary */
/*
Catching the recruiter's eye with a powerful summary section

    What is a LinkedIn Summary?
        A LinkedIn Summary is your first impression to a recruiter.
        It's your elevator pitch!

    Your summary helps you rank in search. It can made you more visible to recruiters.

    What a recruiter sees:
        . What do they see when they view your profile?
        . What do you want them to see?
        . What is the one piece of information about you that you'd want them  to know?
    
    Capture attention with a strong opening statement
        . Frontend developer with experience developing websites and web applications.
        . React developer with a strong passion about accessibility and testing

    Use keywords to rank higher
        . Search for job posting that intrests you
        . Take note of the technologies and skills they list
        . Keep your list in mind while your write your summary
    
    Showcase your best side
        . List your biggest projects
        . Talk about most impressive accomplishments
        . Write about what you love doing
        . Write about why you're excited about coding

    Check your grammar/spelling
        . Keep it professional
        . Ask a friend to review your summary
        . Ask a Scrimba student to give it a once over

    What now?
        . Update your linkedIn summary
        . Share your bio in this https://discord.com/channels/@me
*/

