/* Lesson 7: Adding past work experience to LinkedIn */
/* 
Using past work experience to get a new dev job
    It's okay if you don't have past work experience as developer!

    Past work history can
        . Showcase your work ethic
        . Highlight your past skills 
        . Demonstrate your communication or mentorship skills
        . Show your commitment

    LinkedIn is your way to highlight what you bring to the table

    Highlight transferable skills
        . Any software tools you know
        . Any work experience
        . Mentorship experience
        . Teamwork skills
        . Problem solving skills

    Make it specific
        . Show your work examples
        . Discuss accomplishments ie: "Led a team of 4" Or "Promoted within a year to manager"
        . Go into detail

    Poor explanation
        .   My responsibilities aincluded receiving calls for 
            customers, formulating support ticket and reporting
            to manager.

    Great explanation
        .   I was amongst the top 10% fastest customer service 
            representatives in the company created a system that was 
            implemented across my division to increase efficiency for 
            all employees.

    What now?
    . Add one past job to your LinkedIn profile
*/

